// Links a run the CV fact gate refused to the one automatic repair run
// job-store.tsx starts for it. Without the link, the refused run stays a red
// "Failed" card even after its repair wrote the PDF, and nothing on it says a
// repair ran: the user reads a finished CV as a failure and debugs a run that
// needs nothing.
//
// The refused run keeps status "error" (it did fail, and its own output is
// still worth reading); `repair` records the repair run's id and how it ended,
// and every surface reads it through repairState() below.

/** @typedef {"running" | "done" | "error" | "gated"} JobStatus */
/** @typedef {{ id: string, status: JobStatus }} JobRepair */

const REPAIR_STEP = {
  done: "Automatic repair finished: the CV PDF was generated by the repair run.",
  error: "The automatic repair run failed too. Open the repair run for its error.",
  gated: "The automatic repair run stopped for review. Open the repair run.",
};

/**
 * How a refused run's repair stands: "running", "repaired", "failed", or null
 * for a run that has no repair (or did not fail).
 * @param {{ status?: string, repair?: JobRepair } | null | undefined} job
 * @returns {"running" | "repaired" | "failed" | null}
 */
export function repairState(job) {
  if (job?.status !== "error" || !job.repair?.id) return null;
  if (job.repair.status === "running") return "running";
  return job.repair.status === "done" ? "repaired" : "failed";
}

/**
 * The refused run, linked to the repair run just started for it.
 * @template {{ steps: { kind: string, label: string, ts: number }[] }} J
 * @param {J} job
 * @param {string} repairId
 * @returns {J & { repair: JobRepair }}
 */
export function withRepairStarted(job, repairId) {
  return { ...job, repair: { id: repairId, status: "running" } };
}

/**
 * The refused run, updated with how its repair ended. A job whose repair is a
 * different run is returned unchanged, so a stale callback cannot overwrite a
 * newer link. The appended step becomes the card's last line.
 * @template {{ repair?: JobRepair, steps: { kind: string, label: string, ts: number }[] }} J
 * @param {J} job
 * @param {string} repairId
 * @param {Exclude<JobStatus, "running">} status
 * @param {number} now
 * @returns {J}
 */
export function withRepairFinished(job, repairId, status, now) {
  if (job.repair?.id !== repairId || job.repair.status !== "running") return job;
  return {
    ...job,
    repair: { id: repairId, status },
    steps: [...job.steps, { kind: "status", label: REPAIR_STEP[status], ts: now }],
  };
}

/**
 * A repair still "running" in storage was cut off by a reload: its own job is
 * restored as an interrupted error, so the refused run's link says the same.
 * @template {{ repair?: JobRepair }} J
 * @param {J} job
 * @returns {J}
 */
export function settleInterruptedRepair(job) {
  if (job?.repair?.status !== "running") return job;
  return { ...job, repair: { ...job.repair, status: "error" } };
}
